"""Write every tested prompt variant out verbatim (deliverable: prompt collection).

Reports are only useful next to the exact text that produced them, so this
dumps the profile registry — system prompt, extraction prompt, techniques and
rationale — to a single reviewable markdown file.

    cd backend
    python -m scripts.prompt_eval.list_variants
"""

from __future__ import annotations

import argparse
from pathlib import Path

from scripts.prompt_eval import common


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=common.REPORT_ROOT / "variants.md")
    args = parser.parse_args()

    from app.services.prompt_profiles import (
        BASELINE_PROFILE_ID,
        EXTRACTION_ARMS,
        PROMPT_PROFILES,
        SYSTEM_ARMS,
    )

    lines = [
        "# Prompt variants under test",
        "",
        "Generated by `scripts/prompt_eval/list_variants.py` from "
        "`app/services/prompt_profiles.py`. The registry is the single source of "
        "truth: production renders the same strings.",
        "",
        "Fixed for every variant: `gemma4:e4b`, `think:false`, `num_ctx 4096`, "
        "`num_predict 512`, `temperature 0`, `seed 42`, `repeat_penalty 1.0`, "
        "`format = <batch JSON schema>`, `num_thread 3`.",
        "",
    ]

    stage_one = [PROMPT_PROFILES[v] for v in SYSTEM_ARMS]
    stage_two = [PROMPT_PROFILES[v] for v in EXTRACTION_ARMS]

    def render(profile) -> None:
        lines.extend(
            [
                f"## {profile.id} — {profile.label}",
                "",
                f"- **Techniques:** {', '.join(profile.techniques)}",
                f"- **Few-shot source:** `{profile.few_shot}`",
                f"- **Output mode:** `{profile.output_mode}`",
                f"- **Notes:** {profile.notes}",
                "",
                "<details><summary>System prompt</summary>",
                "",
                "```jinja",
                profile.system_template.strip(),
                "```",
                "",
                "</details>",
                "",
                "<details><summary>Extraction prompt</summary>",
                "",
                "```jinja",
                profile.extraction_template.strip(),
                "```",
                "",
                "</details>",
                "",
            ]
        )

    lines.extend(["## Stage 0 — baseline", ""])
    render(PROMPT_PROFILES[BASELINE_PROFILE_ID])
    lines.extend(["## Stage 1 — system-prompt arms (extraction held at baseline)", ""])
    for profile in stage_one:
        render(profile)
    lines.extend(["## Stage 2 — extraction-prompt arms (system held at baseline)", ""])
    for profile in stage_two:
        render(profile)
    lines.extend(
        [
            "## Stage 3 — combinations",
            "",
            "`V13`–`V15` are generated by "
            "`combination_profile()` from the Stage 1/2 leaderboard "
            "(`compare.py --emit-stage3`), so their text is whatever the two "
            "winning arms contain. They are intentionally absent from the "
            "static registry: choosing them in advance would be a guess.",
            "",
        ]
    )

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(PROMPT_PROFILES)} variant(s) -> {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
